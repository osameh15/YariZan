CREATE TABLE IF NOT EXISTS devices (
    hwid CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    customer_name VARCHAR(120) NOT NULL DEFAULT '',
    notes VARCHAR(1000) NOT NULL DEFAULT '',
    serial VARCHAR(150) CHARACTER SET ascii NULL,
    trial_used TINYINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_seen_at DATETIME NULL,
    issued_at DATETIME NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS trial_grants (
    hwid CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    nonce CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    remaining TINYINT UNSIGNED NOT NULL,
    signature VARCHAR(100) CHARACTER SET ascii NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (hwid, nonce),
    FOREIGN KEY (hwid) REFERENCES devices(hwid)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rate_limits (
    bucket CHAR(64) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
    hits INT UNSIGNED NOT NULL DEFAULT 0,
    expires_at BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    action VARCHAR(40) NOT NULL,
    hwid CHAR(64) CHARACTER SET ascii NULL,
    actor VARCHAR(120) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
