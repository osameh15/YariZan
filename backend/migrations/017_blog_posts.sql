## از یک اشارهٔ کوچک شروع کنید

به‌جای توضیح کامل، فقط توجه کودک را به یک بخش از مسئله جلب کنید. بعد کمی فرصت بدهید تا خودش آن را بررسی کند. چند سؤال پشت‌سرهم می‌تواند بازی را شبیه پرسش‌وپاسخ درسی کند؛ یک پرسش کافی است، بعد به پاسخ یا حرکت بعدی او نگاه کنید.

اگر اشارهٔ اول کافی نبود، یک قدم را با هم انجام دهید. مثلاً دو شیء را با هم بشمارید و ادامه را به او بسپارید. اگر باز هم دشوار بود، می‌توانید همان ایده را بیرون از صفحه و با چند وسیلهٔ آشنا امتحان کنید. هدف تمام‌کردن سریع مرحله نیست؛ می‌خواهیم بفهمیم کودک برای قدم بعدی به چه کمکی نیاز دارد.

