یاریزان برای شش پایهٔ دبستان صفحهٔ محصول جداگانه دارد و بازی‌های مستقلی مانند «عددساز کوچولو» و «دسته‌ساز کوچک» نیز در بخش محصولات ویژه معرفی می‌شوند. مجوز هر محصول جداست؛ خرید یک بازی مستقل به معنی خرید همهٔ پایه‌ها نیست.

وضعیت عرضه و قیمت جاری را در صفحهٔ همان محصول ببینید. اگر محصولی «به‌زودی» است، معرفی آن به معنی فعال‌بودن فروش یا دسترسی به برنامهٔ آماده نیست.

## ۲. برنامه را از بخش دریافت رسمی سایت بگیرید

در بخش «دانلود برنامه»، پایه یا محصول موردنظر را انتخاب کنید. پیش از دریافت، مشخصات نسخه و نیازمندی‌های نوشته‌شده در همان صفحه را بخوانید. نسخه‌های یاریزان برای ویندوز عرضه می‌شوند؛ صفحهٔ دریافت، اطلاعات نسخهٔ ۳۲ یا ۶۴ بیتی و فایل منتشرشده را نشان می‌دهد.

اگر برای یک محصول هنوز فایل منتشر نشده است، از صفحهٔ پشتیبانی پیگیری کنید. از نصب‌کننده‌ای استفاده کنید که از مسیر رسمی دریافت کرده‌اید و اگر کد SHA-256 در صفحه آمده است، برای بررسی یکسان‌بودن فایل از آن استفاده کنید.

## ۳. همان رایانه را به حساب متصل کنید

در برنامهٔ ویندوز، مسیر اتصال حساب را دنبال کنید. صفحهٔ اتصال در مرورگر و کد پیامکی برای تأیید شمارهٔ همراه به شما کمک می‌کنند. کد موقت و کد پیامک را فقط در صفحهٔ مربوط به همان فرایند وارد کنید.

پس از اتصال، وارد بخش «دستگاه‌های من» شوید و یک نام آشنا مانند «رایانهٔ خانه» انتخاب کنید. اگر چند دستگاه به یک شماره متصل‌اند، نام‌ها کمک می‌کنند هنگام ورود یا خرید آن‌ها را از هم تشخیص دهید. نام، جای شناسهٔ واقعی دستگاه را در بررسی مالکیت نمی‌گیرد.

## ۴. پیش از خرید، تجربهٔ محصول را بررسی کنید

برای محصول‌هایی که آزمایش آن‌ها فعال است، فرصت‌های آزمایش را در خود برنامه ببینید. شروع فرصت آزمایش و دریافت مجوز به اتصال اینترنت نیاز دارد. شرایط نمایش‌داده‌شده در برنامه را بررسی کنید و زمان آزمایش را به شناخت روش بازی و تناسب آن با کودک اختصاص دهید.

پس از دریافت مجوز معتبر، همان محصول برای همان دستگاه به‌صورت آفلاین هم قابل استفاده است. برای خرید، صدور یا بررسی تازهٔ مجوز و کارهای مربوط به حساب، اتصال اینترنت همچنان لازم است.

## ۵. دستگاه مقصد را پیش از پرداخت کنترل کنید

در صفحهٔ بررسی سفارش، نام محصول، مبلغ جاری و نام و شناسهٔ دستگاهی را که مجوز برای آن ثبت می‌شود بخوانید. اگر قصد خرید برای رایانهٔ دیگری دارید، پیش از پرداخت مسیر «خرید برای دستگاه دیگر» را دنبال کنید و حساب همان دستگاه را انتخاب کنید.

پس از خرید، برنامه را روی دستگاه مقصد باز کنید تا مجوز محصول را دریافت کند. اگر در دریافت فایل، اتصال حساب یا تشخیص دستگاه به مشکل خوردید، همراه با توضیح مرحله‌ای که در آن هستید با پشتیبانی تماس بگیرید؛ رمز عبور یا کد یک‌بارمصرف را برای دیگران نفرستید.

